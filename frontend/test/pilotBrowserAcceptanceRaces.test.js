import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const evidence = readFileSync(
  new URL('../../scripts/acceptance-browser-evidence-history.mjs', import.meta.url), 'utf8');
const review = readFileSync(
  new URL('../../scripts/acceptance-browser-review-inbox.mjs', import.meta.url), 'utf8');

test('cross-tenant outage gate foregrounds the stale tab before waiting for 503', () => {
  const start = evidence.indexOf('const otherRegistration = await otherRegistrationRequest;');
  const end = evidence.indexOf("console.log('PASS: cross-tenant browser login", start);
  assert.ok(start >= 0 && end > start);
  const scenario = evidence.slice(start, end);
  const foreground = scenario.indexOf('await page.bringToFront();');
  const focus = scenario.indexOf("window.dispatchEvent(new Event('focus'))");
  const authority = scenario.indexOf('await firstUnavailableProfile;');
  assert.ok(foreground >= 0 && focus > foreground && authority > focus,
    'the foreground event must precede the awaited real 503 HTTP');
  assert.match(scenario, /await page\.getByRole\('alert'\)\.getByText\('No se pudo verificar tu sesión'\)\.waitFor\(\)/);
  assert.match(scenario, /assert\.equal\(await panel\.count\(\), 0/);
  assert.match(scenario, /assert\.equal\(await page\.getByTitle\('Monitoreo'\)\.count\(\),\s*0/);
  assert.match(scenario, /await page\.unroute\('\*\*\/api\/v1\/auth\/me', blockedProfileRoute\)/);
});

test('lost review ACK is never generated by fetch-then-abort on one Playwright Route', () => {
  const start = review.indexOf("let reviewPostCount = 0;");
  const end = review.indexOf('const sealedBeforeReload = await reviewJournalMetadata(page);', start);
  assert.ok(start >= 0 && end > start);
  const scenario = review.slice(start, end);
  const abortAt = scenario.indexOf("await route.abort('failed');");
  const submitAt = scenario.indexOf('await context.request.post(originalUrl,');
  assert.ok(abortAt >= 0 && submitAt > abortAt,
    'abort the browser route before performing a single independent real server request');
  assert.doesNotMatch(scenario, /const actual = await route\.fetch\(\)/);
  assert.match(scenario, /originalJson = route\.request\(\)\.postData\(\)/);
  assert.match(scenario, /data: originalJson/);
  assert.match(scenario, /'x-sedeagro-request': '1'/);
  assert.match(scenario, /'x-tenant-id': ownerA\.tenant\.id/);
  assert.match(scenario, /assert\.equal\(committed\.status\(\), 200/);
  assert.match(scenario, /assert\.equal\(\(await committed\.json\(\)\)\.replayed,false/);
  assert.match(scenario, /const committedReview = await reviewCommit/);
  assert.match(scenario, /assert\.equal\(committedReview\.ok, true/);
  assert.match(scenario, /assert\.equal\(reviewPostCount,1/);
  assert.doesNotMatch(scenario, /route\.fulfill\(\{\s*status:\s*200/);
});
